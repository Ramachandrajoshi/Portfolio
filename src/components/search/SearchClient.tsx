'use client';

import { useEffect, useRef, useState } from 'react';
import { BASE_PATH } from '@/lib/urls';

interface PagefindResult {
  url: string;
  excerpt: string;
  meta: { title?: string; type?: string };
}
interface Pagefind {
  search: (q: string) => Promise<{ results: { id: string; data: () => Promise<PagefindResult> }[] }>;
  init?: () => Promise<void>;
}

type State = { kind: 'idle' } | { kind: 'loading' } | { kind: 'unavailable' } | { kind: 'results'; query: string; items: PagefindResult[] };

/**
 * Static full-text search. Pagefind builds a chunked index of every page's
 * data-pagefind-body at build time; this client downloads only the index fragments a
 * query needs. Reads ?q= so the plain HTML search forms work as entry points.
 */
export function SearchClient() {
  const inputRef = useRef<HTMLInputElement>(null);
  const [state, setState] = useState<State>({ kind: 'idle' });
  const pagefind = useRef<Pagefind | null>(null);

  async function load(): Promise<Pagefind | null> {
    if (pagefind.current) return pagefind.current;
    try {
      const url = `${BASE_PATH}/pagefind/pagefind.js`;
      const mod = (await import(/* webpackIgnore: true */ /* turbopackIgnore: true */ url)) as Pagefind;
      await mod.init?.();
      pagefind.current = mod;
      return mod;
    } catch {
      setState({ kind: 'unavailable' });
      return null;
    }
  }

  async function run(q: string) {
    const term = q.trim();
    const pf = await load();
    if (!term) return setState({ kind: 'idle' });
    if (!pf) return;
    const search = await pf.search(term);
    const items = await Promise.all(search.results.slice(0, 20).map((r) => r.data()));
    setState({ kind: 'results', query: term, items });
  }

  useEffect(() => {
    const q = new URLSearchParams(window.location.search).get('q') ?? '';
    if (q && inputRef.current) {
      inputRef.current.value = q;
      void run(q);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- run once on mount
  }, []);

  return (
    <div>
      <form
        role="search"
        onSubmit={(e) => {
          e.preventDefault();
          const query = inputRef.current?.value ?? '';
          const url = new URL(window.location.href);
          url.searchParams.set('q', query);
          window.history.replaceState(null, '', url);
          setState({ kind: 'loading' });
          void run(query);
        }}
        className="flex max-w-2xl gap-2"
      >
        <label htmlFor="site-search" className="sr-only">Search the site</label>
        <input
          id="site-search"
          name="q"
          type="search"
          ref={inputRef}
          placeholder="e.g. idempotency, KV cache, tenant isolation"
          className="h-12 flex-1 rounded-md border border-border-strong bg-surface px-4 text-base placeholder:text-subtle"
          data-testid="search-input"
        />
        <button type="submit" className="h-12 rounded-md bg-accent px-5 font-medium text-accent-contrast hover:bg-accent-strong">Search</button>
      </form>
      <div aria-live="polite" className="mt-8" data-testid="search-results">
        {state.kind === 'loading' ? <p className="text-muted">Searching…</p> : null}
        {state.kind === 'unavailable' ? (
          <p className="text-muted">The search index is not available (it is generated by the production build).</p>
        ) : null}
        {state.kind === 'results' ? (
          <>
            <p className="text-sm text-muted">
              {state.items.length === 0 ? `No results for “${state.query}”.` : `${state.items.length} result${state.items.length === 1 ? '' : 's'} for “${state.query}”`}
            </p>
            <ol className="mt-4 space-y-4">
              {state.items.map((r) => (
                <li key={r.url} className="card p-5">
                  {r.meta.type ? <p className="eyebrow">{r.meta.type}</p> : null}
                  <a href={r.url} className="mt-1 block font-display text-lg font-semibold hover:text-accent">{r.meta.title ?? r.url}</a>
                  {/* Pagefind excerpts contain only <mark> highlighting of indexed text. */}
                  <p className="mt-1 text-sm text-muted [&_mark]:bg-highlight/25 [&_mark]:text-fg" dangerouslySetInnerHTML={{ __html: r.excerpt }} />
                </li>
              ))}
            </ol>
          </>
        ) : null}
      </div>
    </div>
  );
}
